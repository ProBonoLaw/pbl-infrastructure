"""Copy allowlisted blobs and typed Table entities without deleting or overwriting data.

Defaults to inventory only. Run from a host that can reach both storage accounts,
using Azure CLI or workload identity with Blob/Table data access. Freeze source writes for
the final --copy run. Queues, file shares, snapshots, and blob versions are outside
this tool's scope; retain the source account until retention and cutover are done.
"""

import argparse
import hashlib
import json
import re
import tempfile
from pathlib import Path

from azure.core import MatchConditions
from azure.core.exceptions import HttpResponseError, ResourceExistsError
from azure.data.tables import TableServiceClient
from azure.identity import DefaultAzureCredential
from azure.storage.blob import BlobServiceClient, BlobType


class MigrationConflict(RuntimeError):
    pass


def entity_data(entity):
    # Timestamp/ETag are generated by Azure. All user values retain SDK EDM types.
    return {key: value for key, value in entity.items() if key != "Timestamp"}


def entity_versions(table):
    return {
        (row["PartitionKey"], row["RowKey"]): row.metadata["etag"]
        for row in table.list_entities(select=["PartitionKey", "RowKey"])
    }


def blob_digest(blob):
    digest = hashlib.sha256()
    for chunk in blob.download_blob().chunks():
        digest.update(chunk)
    return digest.digest()


def copy_blob(source, destination):
    properties = source.get_blob_properties()
    if properties.blob_type != BlobType.BLOCKBLOB:
        raise MigrationConflict("This copy tool supports block blobs only")
    tags = source.get_blob_tags()
    with tempfile.SpooledTemporaryFile(max_size=8 * 1024 * 1024) as payload:
        source.download_blob(
            etag=properties.etag, match_condition=MatchConditions.IfNotModified
        ).readinto(payload)
        payload.seek(0)
        digest = hashlib.file_digest(payload, "sha256").digest()
        payload.seek(0)
        try:
            destination.upload_blob(
                payload,
                overwrite=False,
                metadata=properties.metadata,
                content_settings=properties.content_settings,
                tags=tags,
            )
            copied = True
        except ResourceExistsError:
            copied = False

    target = destination.get_blob_properties()
    headers = ("content_type", "content_encoding", "content_language",
               "content_disposition", "cache_control")
    if (blob_digest(destination) != digest
            or target.metadata != properties.metadata
            or destination.get_blob_tags() != tags
            or any(getattr(target.content_settings, field) !=
                   getattr(properties.content_settings, field) for field in headers)):
        raise MigrationConflict("Destination blob differs; no existing data was overwritten")
    if (source.get_blob_properties().etag != properties.etag
            or source.get_blob_tags() != tags):
        raise MigrationConflict("Source blob changed during copy; freeze writes before retrying")
    return copied


def copy_entity(source, destination, entity):
    data = entity_data(entity)
    partition, row = data["PartitionKey"], data["RowKey"]
    try:
        destination.create_entity(data)
        copied = True
    except ResourceExistsError:
        copied = False
    if entity_data(destination.get_entity(partition, row)) != data:
        raise MigrationConflict("Destination entity differs; no existing data was overwritten")
    if source.get_entity(partition, row).metadata["etag"] != entity.metadata["etag"]:
        raise MigrationConflict("Source entity changed during copy; freeze writes before retrying")
    return copied


def select_named(items, allowed):
    items = list(items)
    if allowed is None:
        return items
    missing = set(allowed) - {item.name for item in items}
    if missing:
        raise MigrationConflict("An allowlisted container or table is missing from the source")
    return [item for item in items if item.name in allowed]


def transfer(source_blobs, target_blobs, source_tables, target_tables, execute=False,
             include_containers=None, include_tables=None):
    containers = [] if include_containers == [] else select_named(
        source_blobs.list_containers(include_metadata=True), include_containers
    )
    tables = [] if include_tables == [] else select_named(source_tables.list_tables(), include_tables)
    summary = {
        "mode": "copy" if execute else "inventory",
        "containers": len(containers), "tables": len(tables),
        "blobs": 0, "entities": 0, "copied_blobs": 0, "copied_entities": 0,
    }
    for container in containers:
        source = source_blobs.get_container_client(container.name)
        blobs = list(source.list_blobs())
        summary["blobs"] += len(blobs)
        if not execute:
            continue
        target = target_blobs.get_container_client(container.name)
        try:
            target.create_container(metadata=container.metadata or {})
        except ResourceExistsError:
            if target.get_container_properties().metadata != (container.metadata or {}):
                raise MigrationConflict("Destination container metadata differs")
        for blob in blobs:
            # List Blobs returns an unquoted ETag; Get Properties quotes it.
            current_etag = source.get_blob_client(blob.name).get_blob_properties().etag
            if current_etag.strip('"') != blob.etag.strip('"'):
                raise MigrationConflict("Source changed after inventory; freeze writes")
            summary["copied_blobs"] += int(copy_blob(
                source.get_blob_client(blob.name), target.get_blob_client(blob.name)
            ))
        if {item.name: item.etag for item in source.list_blobs()} != {
            item.name: item.etag for item in blobs
        }:
            raise MigrationConflict("Source blob inventory changed during copy")
    for table in tables:
        source = source_tables.get_table_client(table.name)
        if not execute:
            summary["entities"] += sum(1 for _ in source.list_entities(
                select=["PartitionKey", "RowKey"]
            ))
            continue
        target = target_tables.create_table_if_not_exists(table.name)
        versions = {}
        for entity in source.list_entities():
            versions[(entity["PartitionKey"], entity["RowKey"])] = entity.metadata["etag"]
            summary["entities"] += 1
            summary["copied_entities"] += int(copy_entity(source, target, entity))
        if entity_versions(source) != versions:
            raise MigrationConflict("Source table inventory changed during copy")
    if execute and (
        (set() if include_containers == [] else {
            item.name for item in select_named(source_blobs.list_containers(), include_containers)
        })
        != {item.name for item in containers}
        or (set() if include_tables == [] else {
            item.name for item in select_named(source_tables.list_tables(), include_tables)
        })
        != {item.name for item in tables}
    ):
        raise MigrationConflict("Source containers/tables changed during copy")
    return summary


def account_name(value):
    if not re.fullmatch(r"[a-z0-9]{3,24}", value):
        raise argparse.ArgumentTypeError("Expected an Azure storage account name")
    return value


def load_profile(path, source_name):
    plan = json.loads(Path(path).read_text(encoding="utf-8"))
    if plan.get("version") != 1:
        raise ValueError("Unsupported migration plan version")
    profile = plan["sources"][source_name]
    source = account_name(profile["account"])
    target = account_name(plan["destinationAccount"])
    if source == target:
        raise ValueError("Source and destination must differ")
    for field in ("containers", "tables"):
        if not isinstance(profile[field], list) or not all(
            isinstance(name, str) and name and "*" not in name for name in profile[field]
        ):
            raise ValueError("Migration profiles require explicit container and table names")
    if source.startswith("dataautomationla") and any(
        name.lower().startswith(("flow", "azure-webjobs-", "azurefunctions"))
        for name in profile["containers"] + profile["tables"]
    ):
        raise ValueError("Legacy Data Automation Functions data must not be migrated")
    return source, target, profile["containers"], profile["tables"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan", type=Path,
                        default=Path(__file__).resolve().parents[1] / "deploy/storage-migration/test.json")
    parser.add_argument("--source", required=True, help="Source profile name in the migration plan")
    parser.add_argument("--copy", action="store_true",
                        help="Copy and verify data; freeze source writes for the final run")
    args = parser.parse_args()
    try:
        source_account, destination_account, containers, tables = load_profile(args.plan, args.source)
    except (ValueError, KeyError, argparse.ArgumentTypeError) as exc:
        parser.error(str(exc))
    credential = DefaultAzureCredential(exclude_interactive_browser_credential=True)
    with credential, BlobServiceClient(
        f"https://{source_account}.blob.core.windows.net", credential=credential
    ) as source_blobs, BlobServiceClient(
        f"https://{destination_account}.blob.core.windows.net", credential=credential
    ) as target_blobs, TableServiceClient(
        f"https://{source_account}.table.core.windows.net", credential=credential
    ) as source_tables, TableServiceClient(
        f"https://{destination_account}.table.core.windows.net", credential=credential
    ) as target_tables:
        try:
            result = transfer(source_blobs, target_blobs, source_tables, target_tables,
                              args.copy, containers, tables)
        except MigrationConflict as exc:
            raise SystemExit(f"Storage operation incomplete: {exc}") from exc
        except HttpResponseError as exc:
            detail = f"HTTP {exc.status_code}, {getattr(exc, 'error_code', None) or 'Azure request failed'}"
            hint = " Check storage data roles and network access." if exc.status_code == 403 else ""
            raise SystemExit(f"Storage operation incomplete: {detail}.{hint}") from exc
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
