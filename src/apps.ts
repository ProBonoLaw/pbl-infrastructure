import * as pulumi from "@pulumi/pulumi";
import {
  applicationinsights,
  network,
  resources,
  web,
} from "@pulumi/azure-native";
import type { web as webInputs } from "@pulumi/azure-native/types/input";

const defaultDocuments = [
  "Default.htm",
  "Default.html",
  "Default.asp",
  "index.htm",
  "index.html",
  "iisstart.htm",
  "default.aspx",
  "index.php",
];
export const anyAllow: webInputs.IpSecurityRestrictionArgs = {
  ipAddress: "Any",
  action: "Allow",
  priority: 2147483647,
  name: "Allow all",
  description: "Allow all access",
};
export function createSite(
  logicalName: string,
  siteName: pulumi.Input<string>,
  group: resources.ResourceGroup,
  plan: web.AppServicePlan,
  delegatedSubnet: network.Subnet,
  appOverrides: Partial<web.WebAppArgs>,
  configOverrides: webInputs.SiteConfigArgs,
  ftpAllowed: boolean,
  scmAllowed: boolean,
) {
  const site = new web.WebApp(
    logicalName,
    {
      name: siteName,
      resourceGroupName: group.name,
      location: "centralus",
      kind: "app,linux",
      identity: { type: "SystemAssigned" },
      enabled: true,
      serverFarmId: pulumi.interpolate`${group.id}/providers/Microsoft.Web/serverfarms/${plan.name}`,
      reserved: true,
      isXenon: false,
      hyperV: false,
      outboundVnetRouting: {
        allTraffic: false,
        applicationTraffic: false,
        contentShareTraffic: false,
        imagePullTraffic: false,
        backupRestoreTraffic: false,
      },
      scmSiteAlsoStopped: false,
      clientAffinityEnabled: false,
      clientAffinityProxyEnabled: false,
      clientCertEnabled: false,
      clientCertMode: "Required",
      hostNamesDisabled: false,
      ipMode: "IPv4",
      containerSize: 0,
      dailyMemoryTimeQuota: 0,
      httpsOnly: true,
      endToEndEncryptionEnabled: false,
      redundancyMode: "None",
      publicNetworkAccess: "Enabled",
      storageAccountRequired: false,
      virtualNetworkSubnetId: delegatedSubnet.id,
      keyVaultReferenceIdentity: "SystemAssigned",
      autoGeneratedDomainNameLabelScope: "TenantReuse",
      ...appOverrides,
      siteConfig: {
        numberOfWorkers: 1,
        defaultDocuments,
        netFrameworkVersion: "v4.0",
        requestTracingEnabled: false,
        remoteDebuggingEnabled: false,
        httpLoggingEnabled: false,
        acrUseManagedIdentityCreds: false,
        logsDirectorySizeLimit: 35,
        detailedErrorLoggingEnabled: false,
        scmType: "GitHubAction",
        use32BitWorkerProcess: false,
        webSocketsEnabled: false,
        alwaysOn: true,
        managedPipelineMode: "Integrated",
        virtualApplications: [
          {
            virtualPath: "/",
            physicalPath: "site\\wwwroot",
            preloadEnabled: true,
          },
        ],
        loadBalancing: "LeastRequests",
        autoHealEnabled: false,
        vnetRouteAllEnabled: false,
        vnetPrivatePortsCount: 0,
        publicNetworkAccess: "Enabled",
        cors: {
          allowedOrigins: ["https://portal.azure.com"],
          supportCredentials: false,
        },
        localMySqlEnabled: false,
        ipSecurityRestrictions: [anyAllow],
        scmIpSecurityRestrictions: [anyAllow],
        scmIpSecurityRestrictionsUseMain: false,
        http20Enabled: false,
        minTlsVersion: "1.2",
        scmMinTlsVersion: "1.2",
        ftpsState: "FtpsOnly",
        // Preserve the imported portal value to avoid an unrelated site update.
        preWarmedInstanceCount: 0,
        functionsRuntimeScaleMonitoringEnabled: false,
        minimumElasticInstanceCount: 1,
        http20ProxyFlag: 0,
        ...configOverrides,
      },
    },
    {
      // Azure adds these site and runtime fields to imported apps. They are
      // generated by the platform, not settings that this program supplies.
      ignoreChanges: [
        "customDomainVerificationId",
        "hostNameSslStates",
        "sshEnabled",
        "siteConfig.appCommandLine",
        "siteConfig.managedServiceIdentityId",
        "siteConfig.nodeVersion",
        "siteConfig.phpVersion",
        "siteConfig.powerShellVersion",
        "siteConfig.publishingUsername",
        "siteConfig.pythonVersion",
        "siteConfig.remoteDebuggingVersion",
        "siteConfig.vnetName",
      ],
    },
  );
  new web.WebAppFtpAllowed(`${logicalName}-ftp-policy`, {
    name: site.name,
    resourceGroupName: group.name,
    allow: ftpAllowed,
  });
  new web.WebAppScmAllowed(`${logicalName}-scm-policy`, {
    name: site.name,
    resourceGroupName: group.name,
    allow: scmAllowed,
  });
  return site;
}

export function hiddenTags(component: applicationinsights.Component) {
  return { "hidden-link: /app-insights-resource-id": component.id };
}
